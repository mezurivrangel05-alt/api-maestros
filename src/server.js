require('dotenv').config();

const express = require('express');
const { Pool } = require('pg');

const app = express();
const port = Number(process.env.PORT || 3000);
const pool = new Pool({ connectionString: process.env.DATABASE_URL });

async function initializeDatabase() {
  await pool.query(`
    CREATE TABLE IF NOT EXISTS maestros (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      nombre TEXT NOT NULL CHECK (length(trim(nombre)) > 0),
      apellido TEXT NOT NULL CHECK (length(trim(apellido)) > 0),
      especialidad TEXT NOT NULL CHECK (length(trim(especialidad)) > 0),
      correo TEXT UNIQUE,
      telefono TEXT,
      created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
      updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
    )
  `);
  await pool.query(`
    INSERT INTO maestros (id, nombre, apellido, especialidad, correo, telefono) VALUES
      (1, 'Ana', 'García', 'Español', 'ana.garcia@example.com', NULL),
      (2, 'Luis', 'Hernández', 'Historia', 'luis.hernandez@example.com', NULL),
      (3, 'María', 'López', 'Ciencias', 'maria.lopez@example.com', NULL),
      (4, 'Alex', 'Maestro de ejemplo', 'Matemáticas', 'alex.maestro@example.com', NULL),
      (5, 'Carlos', 'Ramírez', 'Inglés', 'carlos.ramirez@example.com', NULL),
      (6, 'Sofía', 'Martínez', 'Geografía', 'sofia.martinez@example.com', NULL)
    ON CONFLICT DO NOTHING
  `);
  await pool.query("SELECT setval(pg_get_serial_sequence('maestros', 'id'), GREATEST((SELECT COALESCE(MAX(id), 1) FROM maestros), 1))");
}

app.use(express.json({ limit: '100kb' }));

app.get('/health', async (_req, res) => {
  try {
    await pool.query('SELECT 1');
    res.json({ status: 'ok', database: 'connected' });
  } catch {
    res.status(503).json({ status: 'error', database: 'unavailable' });
  }
});

app.get('/api/maestros', async (req, res, next) => {
  try {
    const limit = Math.min(Math.max(Number.parseInt(req.query.limit, 10) || 100, 1), 500);
    const offset = Math.max(Number.parseInt(req.query.offset, 10) || 0, 0);
    const { rows } = await pool.query(
      'SELECT id, nombre, apellido, especialidad, correo, telefono, created_at, updated_at FROM maestros ORDER BY id LIMIT $1 OFFSET $2',
      [limit, offset],
    );
    res.json({ data: rows, pagination: { limit, offset } });
  } catch (error) { next(error); }
});

app.get('/api/maestros/:id', async (req, res, next) => {
  try {
    if (!/^\d+$/.test(req.params.id)) return res.status(400).json({ error: 'El id debe ser un entero positivo.' });
    const { rows } = await pool.query(
      'SELECT id, nombre, apellido, especialidad, correo, telefono, created_at, updated_at FROM maestros WHERE id = $1',
      [req.params.id],
    );
    if (!rows[0]) return res.status(404).json({ error: 'Maestro no encontrado.' });
    res.json(rows[0]);
  } catch (error) { next(error); }
});

app.post('/api/maestros', async (req, res, next) => {
  try {
    const { nombre, apellido, especialidad, correo = null, telefono = null } = req.body || {};
    if (![nombre, apellido, especialidad].every(value => typeof value === 'string' && value.trim())) {
      return res.status(400).json({ error: 'nombre, apellido y especialidad son obligatorios.' });
    }
    const { rows } = await pool.query(
      'INSERT INTO maestros (nombre, apellido, especialidad, correo, telefono) VALUES ($1, $2, $3, $4, $5) RETURNING *',
      [nombre.trim(), apellido.trim(), especialidad.trim(), correo, telefono],
    );
    res.status(201).json(rows[0]);
  } catch (error) { next(error); }
});

app.put('/api/maestros/:id', async (req, res, next) => {
  try {
    if (!/^\d+$/.test(req.params.id)) return res.status(400).json({ error: 'El id debe ser un entero positivo.' });
    const { nombre, apellido, especialidad, correo = null, telefono = null } = req.body || {};
    if (![nombre, apellido, especialidad].every(value => typeof value === 'string' && value.trim())) {
      return res.status(400).json({ error: 'nombre, apellido y especialidad son obligatorios.' });
    }
    const { rows } = await pool.query(
      'UPDATE maestros SET nombre=$1, apellido=$2, especialidad=$3, correo=$4, telefono=$5, updated_at=now() WHERE id=$6 RETURNING *',
      [nombre.trim(), apellido.trim(), especialidad.trim(), correo, telefono, req.params.id],
    );
    if (!rows[0]) return res.status(404).json({ error: 'Maestro no encontrado.' });
    res.json(rows[0]);
  } catch (error) { next(error); }
});

app.delete('/api/maestros/:id', async (req, res, next) => {
  try {
    if (!/^\d+$/.test(req.params.id)) return res.status(400).json({ error: 'El id debe ser un entero positivo.' });
    const { rowCount } = await pool.query('DELETE FROM maestros WHERE id=$1', [req.params.id]);
    if (!rowCount) return res.status(404).json({ error: 'Maestro no encontrado.' });
    res.status(204).end();
  } catch (error) { next(error); }
});

app.use((_req, res) => res.status(404).json({ error: 'Ruta no encontrada.' }));
app.use((error, _req, res, _next) => {
  if (error.code === '23505') return res.status(409).json({ error: 'El correo ya está registrado.' });
  console.error(error);
  res.status(500).json({ error: 'Error interno del servidor.' });
});

let server;
initializeDatabase()
  .then(() => {
    server = app.listen(port, '0.0.0.0', () => console.log(`API de maestros escuchando en el puerto ${port}`));
  })
  .catch(error => {
    console.error('No se pudo inicializar la base de datos:', error);
    process.exit(1);
  });

const shutdown = () => {
  const closePool = async () => { await pool.end(); process.exit(0); };
  if (server) server.close(closePool);
  else closePool();
};
process.on('SIGTERM', shutdown);
process.on('SIGINT', shutdown);
